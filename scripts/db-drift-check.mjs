import { execSync } from 'child_process';

console.log('🔍 Running Schema Drift Verification Gate...');

const user = process.env.DB_USER || 'postgres';
const pass = process.env.DB_PASS || 'postgrespassword';
const host = process.env.DB_HOST || 'localhost';
const port = process.env.DB_PORT || '5433';
const dbName = process.env.DB_NAME || 'portfolio_test_db';

const defaultDbUrl = `postgres://${user}:${pass}@${host}:${port}/${dbName}`;

try {
  // 1. Run drizzle-kit generate
  console.log('Running drizzle-kit generate...');
  execSync('npx drizzle-kit generate', {
    env: { ...process.env, DATABASE_URL: process.env.DATABASE_URL || defaultDbUrl },
    stdio: 'inherit',
  });

  // 2. Check git status under drizzle/
  const gitStatus = execSync('git status --porcelain drizzle/', { encoding: 'utf-8' }).trim();

  if (gitStatus.length > 0) {
    console.error('❌ SCHEMA DRIFT DETECTED!');
    console.error(
      'The following migration/snapshot changes were generated by drizzle-kit generate:'
    );
    console.error(gitStatus);
    console.error('\nPlease commit all schema changes and regenerated migrations before merging.');
    process.exit(1);
  }

  console.log(
    '✅ PASS: Zero schema drift detected. Migration state is 100% in sync with Drizzle schema.'
  );
  process.exit(0);
} catch (error) {
  console.error('❌ Error executing schema drift check:', error.message || error);
  process.exit(1);
}
